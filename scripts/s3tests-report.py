# The test categories follow s3s v0.17.0 scripts/report-s3tests.py (`_MODULE_CATEGORIES`,
# `_S3_PATTERNS` and `classify_test`), applied to pytest node ids rather than junit attributes.
"""Write compat/s3-tests.md from every compat/s3-tests/<label>.json of scripts/s3tests.sh.

    python3 -I scripts/s3tests-report.py

The report depends only on those files, so the same inputs give a byte-identical report.
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INPUT_DIR = ROOT / "compat" / "s3-tests"
OUTPUT = ROOT / "compat" / "s3-tests.md"
COMMAND = "python3 -I scripts/s3tests-report.py"
OUTCOMES = ("passed", "failed", "error", "skipped")
# Every test lives here; the report drops it from ids to keep the tables readable.
TEST_DIR = "s3tests/functional/"

# Modules other than test_s3 are one category each.
_MODULE_CATEGORIES = {
    "test_headers": "headers",
    "test_iam": "iam",
    "test_s3select": "s3-select",
    "test_sns": "sns",
    "test_sts": "sts",
    "test_utils": "utils",
}

# test_s3 is split by keywords in the test name; the first matching pattern wins.
_S3_PATTERNS = [
    (re.compile(r"object_lock"), "object-lock"),
    (re.compile(r"presigned"), "presigned"),
    (re.compile(r"multipart"), "multipart"),
    (re.compile(r"sse_|_sse_|sse$|encryption|encrypted|_enc_|_kms_"), "encryption"),
    (re.compile(r"versioning|versioned|delete_marker"), "versioning"),
    (re.compile(r"lifecycle"), "lifecycle"),
    (re.compile(r"cors"), "cors"),
    (re.compile(r"post_object"), "post-object"),
    (re.compile(r"_tag"), "tagging"),
    (re.compile(r"acl"), "acl"),
    (re.compile(r"access_bucket|block_public|ignore_public|public_block"), "acl"),
    (re.compile(r"_policy|policy_"), "policy"),
    (re.compile(r"bucket_list|listv2"), "list-objects"),
    (re.compile(r"logging"), "logging"),
    (re.compile(r"delete"), "delete"),
    (re.compile(r"restore"), "restore"),
    (re.compile(r"ranged"), "range-get"),
    (re.compile(r"copy"), "copy"),
    (re.compile(r"bucket"), "bucket"),
]


def classify(test_id: str) -> str:
    path, name = test_id.split("::", 1)
    module = path.rsplit("/", 1)[-1].removesuffix(".py")
    if module != "test_s3":
        return _MODULE_CATEGORIES.get(module, "other")
    for pattern, category in _S3_PATTERNS:
        if pattern.search(name):
            return category
    return "object"


def load() -> tuple[str, dict[str, dict]]:
    runs = {}
    for path in sorted(INPUT_DIR.glob("*.json")):
        run = json.loads(path.read_text(encoding="utf-8"))
        bad = {o for o in run["tests"].values() if o not in OUTCOMES}
        if bad:
            sys.exit(f"{path}: unknown outcomes {sorted(bad)}")
        runs[path.stem] = run
    if not runs:
        sys.exit(f"no results in {INPUT_DIR}; run scripts/s3tests.sh first")
    refs = {run["s3tests_ref"] for run in runs.values()}
    # Rates from different suites side by side would compare different tests.
    if len(refs) > 1:
        sys.exit(f"inputs use different s3-tests refs {sorted(refs)}; rerun every label")
    return refs.pop(), runs


def count(outcomes) -> dict[str, int]:
    counts = dict.fromkeys(OUTCOMES, 0)
    for outcome in outcomes:
        counts[outcome] += 1
    return counts


def rate(passed: int, total: int) -> str:
    if not total:
        return "n/a"
    # Integer arithmetic, rounded down: 100.0% only when everything passed.
    permille = 1000 * passed // total
    return f"{permille // 10}.{permille % 10}%"


def short(test_id: str) -> str:
    return test_id.removeprefix(TEST_DIR).replace("|", "\\|")


def render(ref: str, runs: dict[str, dict]) -> str:
    labels = list(runs)
    inputs = ", ".join(f"`compat/s3-tests/{label}.json`" for label in labels)
    out = [
        "# ceph s3-tests compatibility",
        "",
        (
            f"Generated by `{COMMAND}` from {inputs}. Do not edit it by hand: run "
            "`scripts/s3tests.sh <label>` for a backend, then the command above."
        ),
        "",
        (
            "Each run starts a fresh s3dal on one backend and runs the whole "
            "[ceph/s3-tests](https://github.com/ceph/s3-tests) suite at "
            f"[`{ref[:12]}`](https://github.com/ceph/s3-tests/tree/{ref}), the ref s3s pins, "
            "with no marker filter."
        ),
        "",
        "How to read it:",
        "",
        (
            "- The pass rate is passed / total, and total counts every collected test, skipped "
            "ones included: a skip is not a pass, and every backend gets the same denominator."
        ),
        (
            "- *failed*: the test body failed, or ran into the per-test timeout. *error*: its "
            "setup or teardown failed. *skipped*: the suite skipped it."
        ),
        (
            "- s3dal has one tenant, so the suite's alt, tenant and IAM users are all the main "
            "user. ACL, policy, IAM and STS results do not measure isolation between users."
        ),
        (
            "- Tests of features s3dal does not implement or deliberately refuses (versioning, "
            "ACLs that grant access, bucket policies, object lock, SSE, object tags, lifecycle, "
            "CORS, logging, POST uploads signed with SigV2, as all of the suite's are, IAM, STS, "
            "SNS, S3 Select) are expected to fail. Some pass anyway because a "
            "refusal is all they check: most s3-select tests compare the results of two queries, "
            "which match when both are refused."
        ),
        (
            "- *s3dal source* is the git tree id of the source that ran, without `compat/`; for "
            "a commit it is `git ls-tree COMMIT | awk -F'\\t' '$2 != \"compat\"' | git mktree`."
        ),
        (
            "- Test ids are relative to `s3tests/functional/`, and tests are put in categories "
            "by the rules of s3s's `scripts/report-s3tests.py`."
        ),
        "",
        "## Summary",
        "",
        "| backend | passed / total | pass rate | failed | error | skipped | s3dal source |",
        "|---|--:|--:|--:|--:|--:|---|",
    ]
    for label, run in runs.items():
        c = count(run["tests"].values())
        total = len(run["tests"])
        out.append(
            f"| {label} | {c['passed']} / {total} | {rate(c['passed'], total)} "
            f"| {c['failed']} | {c['error']} | {c['skipped']} | `{run['s3dal_source']}` |"
        )

    categories: dict[str, set[str]] = {}
    for run in runs.values():
        for test_id in run["tests"]:
            categories.setdefault(classify(test_id), set()).add(test_id)

    out += [
        "",
        "## Pass rate by category",
        "",
        "| category | tests | " + " | ".join(labels) + " |",
        "|---|--:|" + "--:|" * len(labels),
    ]
    for category in sorted(categories):
        ids = categories[category]
        cells = []
        for run in runs.values():
            passed = sum(run["tests"].get(t) == "passed" for t in ids)
            cells.append(f"{rate(passed, len(ids))} ({passed})")
        out.append(f"| {category} | {len(ids)} | " + " | ".join(cells) + " |")

    out += [
        "",
        "## Tests that do not pass, by category",
        "",
        (
            "Each list holds the tests that do not pass on at least one backend, with every "
            "backend's outcome; *missing* means that run did not collect the test."
        ),
    ]
    for category in sorted(categories):
        rows = sorted(
            t
            for t in categories[category]
            if any(run["tests"].get(t) != "passed" for run in runs.values())
        )
        if not rows:
            continue
        not_passing = ", ".join(
            f"{label} {sum(run['tests'].get(t) != 'passed' for t in rows)}"
            for label, run in runs.items()
        )
        size = len(categories[category])
        out += [
            "",
            "<details>",
            (
                f"<summary>{category}, {size} test{'' if size == 1 else 's'}; "
                f"not passing: {not_passing}</summary>"
            ),
            "",
            "| test | " + " | ".join(labels) + " |",
            "|---|" + "---|" * len(labels),
        ]
        for t in rows:
            outcomes = (run["tests"].get(t, "missing") for run in runs.values())
            out.append(f"| `{short(t)}` | " + " | ".join(outcomes) + " |")
        out += ["", "</details>"]
    return "\n".join(out) + "\n"


def main() -> None:
    if len(sys.argv) != 1:
        sys.exit(f"usage: {COMMAND}")
    ref, runs = load()
    OUTPUT.write_text(render(ref, runs), encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)} from {len(runs)} result file(s)")


if __name__ == "__main__":
    main()
